export function pendingBackupExportLabels(t: Translate, locale = t.locale): PendingExportLabels {
  return {
    title: t("Resume pending encrypted backup"),
    destination: t("Choose a destination before entering your saved recovery code. The encrypted backup stays on this device until it is saved or explicitly discarded."),
    choose: t("Choose backup destination"),
    choosing: t("Selecting a backup destination…"),
    code: t("Saved recovery code"),
    continue: t("Continue pending export"),
    authenticating: t("Opening the original encrypted backup…"),
    failedCode: t("The saved code could not unlock this backup."),
    limited: t("Too many attempts. Close and start again to retry."),
    ready: t("The original encrypted backup is ready to save."),
    save: t("Save encrypted backup"),
    saving: t("Saving encrypted backup…"),
    keep: t("Keep pending backup and close"),
    kept: t("The pending encrypted backup has been kept on this device."),
    discard: t("Discard pending backup"),
    discardWarning: t("Discarding removes the pending encrypted copy from this device. A backup file you already saved is kept."),
    confirmDiscard: t("Permanently discard pending backup"),
    back: t("Go back"),
    repairTitle: t("Pending backup is incomplete or damaged"),
    repairDescription: t("Remove the incomplete or damaged pending copy to start a new backup. This cannot recover a lost recovery code."),
    repair: t("Remove damaged pending backup"),
    confirmRepair: t("Remove damaged pending copy"),
    changing: t("Updating the pending backup…"),
    failedAction: t("The pending backup could not be changed. Check it again before continuing."),
    checking: t("Checking for a pending encrypted backup…"),
    stateFailed: t("Could not check for a pending backup. Try again."),
    retryState: t("Check pending backup"),
    savedPending: t("Encrypted backup saved. Its pending encrypted copy is still on this device. You can discard it on your next visit."),
    details: (createdAt, wireSize) => {
      const milliseconds = BigInt(createdAt);
      const time = milliseconds <= 8_640_000_000_000_000n ? new Date(Number(milliseconds)).toLocaleString(locale) : t('{value} ms', { value: createdAt });
      return t('Created {time} · Encrypted file size: {size}', { time, size: formatBytes(wireSize) });
    },
  };
}
