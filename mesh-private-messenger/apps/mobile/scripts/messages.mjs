#!/usr/bin/env node

// Builds src/locales/en.ts from the English the app shows: every `t("…")`,
// `msg("…")` and `t.plural("…", "…", n)` call with literal text, grouped by
// the file it first appears in so translators see where it is used. Then
// says what each other language's catalog lacks or has left over.
//
//   node scripts/messages.mjs           write en.ts and report
//   node scripts/messages.mjs --check   fail if en.ts is out of date

import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const app = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const source = join(app, 'src');
const output = join(source, 'locales', 'en.ts');

// A string literal in any of the three quotes, without interpolation.
const literal = String.raw`(?:"((?:\\.|[^"\\])*)"|'((?:\\.|[^'\\])*)'|` + '`' + String.raw`((?:\\.|[^` + '`' + String.raw`\\$])*)` + '`)';
const single = new RegExp(String.raw`(?<![\w.$])(?:t|msg)\(\s*${literal}`, 'g');
const plural = new RegExp(String.raw`(?<![\w.$])t\.plural\(\s*${literal}\s*,\s*${literal}`, 'g');

const unescape = (text) => text.replace(/\\(u\{?[0-9a-fA-F]+\}?|.)/g, (_, code) => {
  if (code.startsWith('u')) return String.fromCodePoint(Number.parseInt(code.replace(/[u{}]/g, ''), 16));
  return { n: '\n', t: '\t' }[code] ?? code;
});
const text = (match, offset) => unescape(match[offset] ?? match[offset + 1] ?? match[offset + 2] ?? '');

export function collect(files = sourceFiles()) {
  const entries = new Map();
  for (const file of files) {
    // Comments may quote a call as an example; only code counts.
    const code = readFileSync(file, 'utf8')
      .replace(/\/\*[\s\S]*?\*\//g, (comment) => comment.replace(/[^\n]/g, ' '))
      .replace(/^\s*\/\/.*$/gm, '');
    const name = relative(source, file);
    const found = [];
    for (const match of code.matchAll(plural)) {
      found.push([match.index, text(match, 4), { one: text(match, 1), other: text(match, 4) }]);
    }
    for (const match of code.matchAll(single)) found.push([match.index, text(match, 1), text(match, 1)]);
    for (const [, key, value] of found.sort((a, b) => a[0] - b[0])) {
      if (!entries.has(key)) entries.set(key, { file: name, value });
    }
  }
  return entries;
}

function sourceFiles(directory = source) {
  return readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const path = join(directory, entry.name);
    if (entry.isDirectory()) return entry.name === 'locales' ? [] : sourceFiles(path);
    return /\.tsx?$/.test(entry.name) && !/\.test\.tsx?$/.test(entry.name) ? [path] : [];
  });
}

const quote = (value) => `'${value.replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\n/g, '\\n')}'`;

export function render(entries) {
  const lines = [
    '// Generated by `npm run messages` from the `t`, `t.plural` and `msg` calls in',
    '// the app. Edit the English in the code, not here.',
    'export const en = {',
  ];
  let file = '';
  for (const [key, entry] of entries) {
    if (entry.file !== file) {
      file = entry.file;
      lines.push(`  // ${file}`);
    }
    const value = typeof entry.value === 'string'
      ? quote(entry.value)
      : `{ one: ${quote(entry.value.one)}, other: ${quote(entry.value.other)} }`;
    lines.push(`  ${quote(key)}: ${value},`);
  }
  lines.push('} as const;', '');
  return lines.join('\n');
}

const scriptPath = fileURLToPath(import.meta.url);
if (process.argv[1] && resolve(process.argv[1]) === scriptPath) {
  const entries = collect();
  const rendered = render(entries);
  if (process.argv.includes('--check')) {
    if (readFileSync(output, 'utf8') !== rendered) {
      console.error('src/locales/en.ts is out of date; run npm run messages.');
      process.exitCode = 1;
    }
  } else {
    writeFileSync(output, rendered);
    console.log(`${entries.size} messages written to src/locales/en.ts.`);
    for (const language of ['es', 'pt', 'fr', 'de', 'ru']) {
      const catalog = readFileSync(join(source, 'locales', `${language}.ts`), 'utf8');
      const present = new Set([...catalog.matchAll(new RegExp(String.raw`^ {2}${literal}\s*:`, 'gm'))].map((match) => text(match, 1)));
      const missing = [...entries.keys()].filter((key) => !present.has(key));
      const extra = [...present].filter((key) => !entries.has(key));
      console.log(`${language}: ${missing.length} to translate, ${extra.length} no longer used`);
    }
  }
}
