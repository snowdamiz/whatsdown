// App-owned facade: validate the public compiler ABI before selecting app calls.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const header = `import { requireNativeModule } from 'expo-modules-core';

type MeshNativeModule = {
  invoke(symbol: string, request: Uint8Array): Promise<Uint8Array>;
};

const native = requireNativeModule<MeshNativeModule>('MeshMessenger');

`;
const identifier = /^[A-Za-z_][A-Za-z0-9_]*$/;
const backupSymbols = new Set([
  'mesh_messenger_backup_create', 'mesh_messenger_backup_preview', 'mesh_messenger_backup_import',
  'mesh_messenger_backup_list', 'mesh_messenger_backup_remove', 'mesh_messenger_backup_overview',
  'mesh_messenger_backup_page', 'mesh_messenger_backup_pending_state', 'mesh_messenger_backup_pending_resume',
  'mesh_messenger_backup_pending_discard', 'mesh_messenger_backup_pending_repair',
]);
function exportsFrom(abi) {
  if (!abi || typeof abi !== 'object' || Array.isArray(abi) || abi.abiVersion !== 1 || !Array.isArray(abi.exports)) throw Error('binding_abi_changed');
  const aliases = new Set(), symbols = new Set();
  for (const row of abi.exports) {
    if (!row || typeof row !== 'object' || Array.isArray(row) ||
        typeof row.meshFunction !== 'string' || !identifier.test(row.meshFunction) ||
        typeof row.symbol !== 'string' || !identifier.test(row.symbol) ||
        aliases.has(row.meshFunction) || symbols.has(row.symbol) ||
        row.request !== 'bytes' || row.response !== 'result<bytes,string>' ||
        !Number.isSafeInteger(row.maxInputBytes) || row.maxInputBytes < 1 || row.maxInputBytes > 67_108_864 ||
        !Number.isSafeInteger(row.maxOutputBytes) || row.maxOutputBytes < 1 || row.maxOutputBytes > 67_108_864 ||
        (Object.hasOwn(row, 'bindingAudience') && row.bindingAudience !== 'native')) throw Error('binding_abi_changed');
    aliases.add(row.meshFunction); symbols.add(row.symbol);
  }
  return abi.exports;
}
export function parseBindings(source, abi) {
  const exports = exportsFrom(abi);
  const rows = [...source.matchAll(/^export const ([A-Za-z_][A-Za-z0-9_]*) = \(request: Uint8Array\): Promise<Uint8Array> => native\.invoke\('([A-Za-z_][A-Za-z0-9_]*)', request\);$/gm)];
  const canonical = rows.length ? header + rows.map(row => row[0] + '\n').join('') : '// No JavaScript bindings were requested.\nexport {};\n';
  if (source !== canonical) throw Error('binding_shape_changed');
  const byAlias = new Map(exports.map(row => [row.meshFunction, row])), seen = new Set();
  for (const [, alias, symbol] of rows) {
    const entry = byAlias.get(alias);
    if (entry?.bindingAudience === 'native') throw Error('native_binding_exposed');
    if (!entry || entry.symbol !== symbol || seen.has(alias)) throw Error('binding_pair_changed');
    seen.add(alias);
  }
  if (seen.size !== exports.filter(row => row.bindingAudience !== 'native').length) throw Error('binding_missing');
  return rows.map(([, alias, symbol]) => ({ alias, symbol }));
}
export function generate(source, abi) {
  const publicRows = parseBindings(source, abi);
  if (publicRows.length !== 175 || publicRows.filter(row => backupSymbols.has(row.symbol)).length !== 11) throw Error('binding_app_policy_changed');
  const rows = publicRows.filter(row => !backupSymbols.has(row.symbol));
  return "// Generated by scripts/generate-scoped-bindings.mjs from validated public ABI.\nimport type { AppLockSession } from '../../src/app-lock';\nexport function createScopedBindings(client: Pick<AppLockSession, 'invoke'>) {\n  return Object.freeze({\n" + rows.map(row=>"    "+row.alias+": (request: Uint8Array) => client.invoke('"+row.symbol+"', request),").join('\n') + "\n  });\n}\nexport type ScopedBindings = ReturnType<typeof createScopedBindings>;\nexport type ScopedClient = AppLockSession & ScopedBindings;\n";
}
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2), check = args.includes('--check');
  const position = args.indexOf('--abi'), abiPath = args[position + 1];
  if (position < 0 || !abiPath || abiPath.startsWith('--') || args.length !== (check ? 3 : 2)) throw Error('binding_abi_path_required');
  const source = readFileSync(new URL('../modules/mesh-messenger/generated/libmessenger_mobile.ts', import.meta.url), 'utf8');
  const abi = JSON.parse(readFileSync(abiPath, 'utf8'));
  const output = new URL('../modules/mesh-messenger/scoped.ts', import.meta.url);
  const result = generate(source, abi);
  if (check) {
    if (readFileSync(output, 'utf8') !== result) throw Error('scoped_bindings_stale');
  } else writeFileSync(output, result);
}
